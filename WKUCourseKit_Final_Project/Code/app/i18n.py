def resolve_language(request: Request) -> str:
    query_language = request.query_params.get("lang")
    if query_language in SUPPORTED_LANGUAGES:
        return query_language
    cookie_language = request.cookies.get(LANGUAGE_COOKIE)
    if cookie_language in SUPPORTED_LANGUAGES:
        return cookie_language
    return DEFAULT_LANGUAGE


def translate(language: str, key: str) -> str:
    return TRANSLATIONS.get(language, TRANSLATIONS[DEFAULT_LANGUAGE]).get(
        key,
        TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key),
    )


def translate_status(language: str, value: str) -> str:
    key = value.replace("-", "_")
    return translate(language, f"badges.{key}")


def translate_course_title(language: str, title: str) -> str:
    if language != "zh":
        return title
    return COURSE_TITLE_TRANSLATIONS_ZH.get(title, title)


def language_url(request: Request, language: str) -> str:
    params = dict(request.query_params)
    params["lang"] = language
    query = urlencode(params)
    return f"{request.url.path}?{query}" if query else request.url.path


def path_with_language(path: str, language: str) -> str:
    separator = "&" if "?" in path else "?"
    return f"{path}{separator}lang={language}"


def format_date(value: datetime | date | None, language: str) -> str:
    if value is None:
        return translate(language, "common.not_loaded")
    if language == "zh":
        return f"{value.year}年{value.month}月{value.day}日"
    if isinstance(value, datetime):
        return value.strftime("%b %d, %Y")
    return value.strftime("%b %d, %Y")


def format_short_date(value: datetime | date | None, language: str) -> str:
    if value is None:
        return translate(language, "common.not_loaded")
    if language == "zh":
        return f"{value.month}月{value.day}日"
    return value.strftime("%b %d")
